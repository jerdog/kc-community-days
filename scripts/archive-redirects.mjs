#!/usr/bin/env node
// Runs after `astro build`. Links shared during a past year (e.g. /speakers/mandi-walls/)
// keep working: for every archived talk, speaker or community page that the current year
// doesn't have, add a 301 from the old address to /<year>/… in dist/_redirects.
// Newest archive wins when two years share a slug.
import { readdir, readFile, writeFile, access } from 'node:fs/promises';
import { resolve } from 'node:path';

const dist = resolve(import.meta.dirname, '..', 'dist');
const exists = (p) => access(p).then(() => true, () => false);
const years = (await readdir(dist, { withFileTypes: true }))
  .filter((d) => d.isDirectory() && /^\d{4}$/.test(d.name))
  .map((d) => d.name)
  .sort()
  .reverse();

const rules = new Map();
for (const year of years) {
  for (const section of ['program', 'speakers', 'communities']) {
    const dir = resolve(dist, year, section);
    if (!(await exists(dir))) continue;
    for (const d of await readdir(dir, { withFileTypes: true })) {
      if (!d.isDirectory()) continue;
      const from = `/${section}/${d.name}/`;
      if (rules.has(from) || (await exists(resolve(dist, section, d.name)))) continue;
      rules.set(from, `/${year}${from}`);
    }
  }
}

if (rules.size) {
  const file = resolve(dist, '_redirects');
  const existing = (await exists(file)) ? await readFile(file, 'utf8') : '';
  const lines = [...rules].flatMap(([from, to]) => [`${from} ${to} 301`, `${from.slice(0, -1)} ${to} 301`]);
  await writeFile(file, `${existing.trimEnd()}\n\n# Pages from past years (generated by scripts/archive-redirects.mjs)\n${lines.join('\n')}\n`);
}
console.log(`archive-redirects: ${rules.size} old link(s) redirected to ${years.length ? years.map((y) => `/${y}/`).join(', ') : 'no archives'}`);
